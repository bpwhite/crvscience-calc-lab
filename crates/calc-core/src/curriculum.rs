#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum Stage {
    Notation,
    Algebra,
    Trigonometry,
    Calculus,
    LinearAlgebra,
    AdvancedCalculus,
    DifferentialEquations,
    ProbabilityStats,
}

impl Stage {
    pub const ALL: [Stage; 8] = [
        Stage::Notation,
        Stage::Algebra,
        Stage::Trigonometry,
        Stage::Calculus,
        Stage::LinearAlgebra,
        Stage::AdvancedCalculus,
        Stage::DifferentialEquations,
        Stage::ProbabilityStats,
    ];

    pub fn index(&self) -> usize {
        match self {
            Stage::Notation => 0,
            Stage::Algebra => 1,
            Stage::Trigonometry => 2,
            Stage::Calculus => 3,
            Stage::LinearAlgebra => 4,
            Stage::AdvancedCalculus => 5,
            Stage::DifferentialEquations => 6,
            Stage::ProbabilityStats => 7,
        }
    }

    pub fn title(&self) -> &'static str {
        match self {
            Stage::Notation => "0. Notation & Symbolic Literacy",
            Stage::Algebra => "I. Algebra Foundations",
            Stage::Trigonometry => "II. Trigonometry & Waves",
            Stage::Calculus => "III. Single-Variable Calculus",
            Stage::LinearAlgebra => "Bridge. Linear Algebra & Eigen-Systems",
            Stage::AdvancedCalculus => "IV. Advanced & Vector Calculus",
            Stage::DifferentialEquations => "V. Ordinary & Partial Differential Equations",
            Stage::ProbabilityStats => "VI. Probability & Statistical Inference",
        }
    }

    pub fn short_label(&self) -> &'static str {
        match self {
            Stage::Notation => "Notation",
            Stage::Algebra => "Algebra",
            Stage::Trigonometry => "Trigonometry",
            Stage::Calculus => "Calculus",
            Stage::LinearAlgebra => "Linear Algebra",
            Stage::AdvancedCalculus => "Advanced Calc",
            Stage::DifferentialEquations => "ODEs & PDEs",
            Stage::ProbabilityStats => "Prob & Stats",
        }
    }
}

