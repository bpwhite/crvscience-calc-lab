#[derive(Debug, Clone)]
pub struct ModuleSpec {
    pub id: &'static str,
    pub code: &'static str,
    pub stage: Stage,
    pub order_in_stage: usize,
    pub title: &'static str,
    pub subtitle: &'static str,
    pub prerequisites: &'static [&'static str],
    pub summary: &'static str,
    pub first_principles_notes: &'static [&'static str],
    pub key_identities: &'static [&'static str],
    pub calculus_bridge: &'static str,
    pub lab_preset: LabPreset,
}

#[derive(Debug, Clone)]
pub struct CurriculumCatalog {
    pub modules: Vec<ModuleSpec>,
}

impl CurriculumCatalog {
    pub fn get(&self, id: &str) -> Option<&ModuleSpec> {
        self.modules.iter().find(|m| m.id == id)
    }

    pub fn by_stage(&self, stage: Stage) -> Vec<&ModuleSpec> {
        self.modules.iter().filter(|m| m.stage == stage).collect()
    }
}

